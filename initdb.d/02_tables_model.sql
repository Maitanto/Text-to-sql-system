\connect subscriptions

DROP TABLE IF EXISTS USERS CASCADE;
DROP TABLE IF EXISTS PLANS CASCADE;
DROP TABLE IF EXISTS SUBSCRIPTIONS CASCADE;
DROP TABLE IF EXISTS PAYMENTS CASCADE;

CREATE TYPE BILLING_PERIOD_ENUM AS ENUM('monthly', 'annual');
CREATE TYPE PAYMENT_METHOD_ENUM AS ENUM('card', 'bank_transfer', 'paypal', 'apple_pay', 'google_pay', 'cash');
CREATE TYPE STATUS_ENUM AS ENUM('pending', 'paid', 'cancelled', 'failed', 'refunded');

CREATE TABLE USERS(
    LOGIN VARCHAR(50) PRIMARY KEY,
    FIRST_NAME VARCHAR(50) NOT NULL,
    LAST_NAME VARCHAR(50) NOT NULL,
    AGE INT CHECK (AGE > 0),
    GENDER VARCHAR(20),
    SIGNUP_DATE DATE NOT NULL
);

CREATE TABLE PLANS(
    NAME VARCHAR(50) PRIMARY KEY,
    PRICE NUMERIC(6, 2) NOT NULL CHECK (PRICE > 0),
    BILLING_PERIOD BILLING_PERIOD_ENUM NOT NULL
);

CREATE TABLE SUBSCRIPTIONS(
    ID VARCHAR(50) PRIMARY KEY,
    USER_LOGIN VARCHAR(50) REFERENCES USERS(LOGIN) NOT NULL,
    START_DATE DATE NOT NULL,
    END_DATE DATE,
    PLANS_NAME VARCHAR(50) REFERENCES PLANS(NAME) NOT NULL
);

CREATE TABLE PAYMENTS(
    ID VARCHAR(50) PRIMARY KEY,
    SUBSCRIPTION_ID VARCHAR(50) REFERENCES SUBSCRIPTIONS(ID) NOT NULL,
    PAYMENT_METHOD PAYMENT_METHOD_ENUM NOT NULL,
    STATUS STATUS_ENUM NOT NULL,
    PAYMENT_DATE DATE NOT NULL
);