SELECT status, COUNT(*) AS payment_count
FROM payments
GROUP BY status
ORDER BY payment_count DESC;

-- How many new users signed up in 2025?

SELECT COUNT(*) AS signups_2025
FROM users
WHERE EXTRACT(YEAR FROM signup_date) = 2025;

-- How many subscriptions have been created for each plan?

SELECT pl.name AS plans_name,
       COUNT(s.id) AS subscription_count
FROM plans pl
LEFT JOIN subscriptions s ON pl.name = s.plans_name
GROUP BY pl.name
ORDER BY subscription_count DESC;

-- List the login, first name, last name, and plan name for users with an active subscription.

SELECT u.login, u.first_name, u.last_name, s.plans_name
FROM users u
JOIN subscriptions s ON u.login = s.user_login
WHERE s.end_date IS NULL;

-- Calculate total revenue collected from paid payments for each billing period.

SELECT pl.billing_period,
       SUM(pl.price) AS total_revenue
FROM payments p
JOIN subscriptions s ON p.subscription_id = s.id
JOIN plans pl ON s.plans_name = pl.name
WHERE p.status = 'paid'
GROUP BY pl.billing_period;

-- Find users who signed up but have never started a subscription.

SELECT u.login, u.first_name, u.last_name, u.signup_date
FROM users u
LEFT JOIN subscriptions s ON u.login = s.user_login
WHERE s.id IS NULL;

-- Find the IDs of subscriptions that have no payments at all.

SELECT s.id
FROM subscriptions s
LEFT JOIN payments p ON s.id = p.subscription_id
WHERE p.id IS NULL;

-- For ended subscriptions, what is the average duration in days per plan?

SELECT plans_name,
       ROUND(AVG(end_date::date - start_date::date), 1) AS avg_duration_days
FROM subscriptions
WHERE end_date IS NOT NULL
GROUP BY plans_name
ORDER BY avg_duration_days DESC;

-- What is the payment cancellation rate percentage for each payment method?

SELECT payment_method,
       COUNT(*) AS total_attempts,
       COUNT(*) FILTER (WHERE status = 'cancelled') AS cancelled_attempts,
       ROUND(
           COUNT(*) FILTER (WHERE status = 'cancelled') * 100.0 / NULLIF(COUNT(*), 0),
           2
       ) AS cancellation_rate_pct
FROM payments
GROUP BY payment_method
ORDER BY cancellation_rate_pct DESC;

-- Identify users who currently have more than one active subscription.

SELECT u.login, u.first_name, u.last_name, COUNT(s.id) AS active_subscription_count
FROM users u
JOIN subscriptions s ON u.login = s.user_login
WHERE s.end_date IS NULL
GROUP BY u.login, u.first_name, u.last_name
HAVING COUNT(s.id) > 1;

-- List the top 10 users by total amount paid across successful payments.

SELECT u.login,
       u.first_name,
       u.last_name,
       SUM(pl.price) AS total_paid
FROM users u
JOIN subscriptions s ON u.login = s.user_login
JOIN plans pl ON s.plans_name = pl.name
