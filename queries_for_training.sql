-- How many customers represent a company?

SELECT COUNT(*) AS corporate_customers
FROM customers
WHERE company_name IS NOT NULL;

-- What is the total quantity of items sold across all transactions?

SELECT SUM(quantity) AS total_units_sold
FROM transactions;

-- List the names and prices of all products released in 2025.

SELECT name, price
FROM products
WHERE EXTRACT(YEAR FROM release_date) = 2025
ORDER BY release_date ASC;

-- What is the average retail price and average production cost across all products?

SELECT ROUND(AVG(price), 2) AS avg_price,
       ROUND(AVG(cost_of_production), 2) AS avg_cost
FROM products;

-- Show all transactions where more than 5 units were bought in a single order.

SELECT id, product_name, customer_login, date_of_transaction, quantity
FROM transactions
WHERE quantity > 5
ORDER BY quantity DESC, id ASC;

-- How many customers do we have per gender?

SELECT gender, COUNT(*) AS customer_count
FROM customers
GROUP BY gender
ORDER BY customer_count DESC;

-- Show the total number of units sold for each product.

SELECT product_name, SUM(quantity) AS total_units
FROM transactions
GROUP BY product_name
ORDER BY total_units DESC;

-- Which products cost more than the average product price?

SELECT name, price
FROM products
WHERE price > (SELECT AVG(price) FROM products)
ORDER BY price DESC;

-- Calculate the total revenue generated by each product, ordered from highest to lowest.

SELECT p.name AS product_name,
       COALESCE(SUM(p.price * t.quantity), 0) AS total_revenue
FROM products p
LEFT JOIN transactions t ON p.name = t.product_name
GROUP BY p.name
ORDER BY total_revenue DESC;

-- Compute the total net profit for each product.

SELECT p.name AS product_name,
       SUM((p.price - p.cost_of_production) * t.quantity) AS total_profit
FROM transactions t
JOIN products p ON t.product_name = p.name
GROUP BY p.name
ORDER BY total_profit DESC;

-- What is the profit margin percentage for each product?

SELECT p.name AS product_name,
       ROUND(
           SUM((p.price - p.cost_of_production) * t.quantity) * 100.0
           / NULLIF(SUM(p.price * t.quantity), 0),
           2
       ) AS profit_margin_pct
FROM products p
JOIN transactions t ON p.name = t.product_name
GROUP BY p.name
ORDER BY profit_margin_pct DESC NULLS LAST;

-- List the login, first name, and last name of customers who have placed more than 5 orders.

SELECT c.login, c.first_name, c.last_name, COUNT(t.id) AS order_count
FROM customers c
JOIN transactions t ON c.login = t.customer_login
GROUP BY c.login, c.first_name, c.last_name
HAVING COUNT(t.id) > 5
ORDER BY order_count DESC;

-- Compare the number of transactions and total units sold between corporate customers and individual consumers.

SELECT CASE WHEN c.company_name IS NOT NULL THEN 'Corporate' ELSE 'Individual' END AS customer_segment,
       COUNT(t.id) AS total_transactions,
       SUM(t.quantity) AS total_units_sold
FROM transactions t
JOIN customers c ON t.customer_login = c.login
GROUP BY customer_segment;

-- How many transactions happened in Q4 2025?

SELECT COUNT(*) AS q4_transactions
FROM transactions
WHERE date_of_transaction >= DATE '2025-10-01'
  AND date_of_transaction <= DATE '2025-12-31';

-- Show monthly revenue and transaction count for 2025, ordered chronologically.

SELECT DATE_TRUNC('month', t.date_of_transaction)::date AS month,
       COUNT(t.id) AS transaction_count,
       SUM(p.price * t.quantity) AS monthly_revenue
FROM transactions t
JOIN products p ON t.product_name = p.name
WHERE EXTRACT(YEAR FROM t.date_of_transaction) = 2025
GROUP BY month
ORDER BY month ASC;

-- What is the average customer age and total quantity purchased by gender?

SELECT c.gender,
       ROUND(AVG(c.age), 1) AS average_age,
       COALESCE(SUM(t.quantity), 0) AS total_units_purchased
FROM customers c
LEFT JOIN transactions t ON c.login = t.customer_login
GROUP BY c.gender;

-- Which product has the highest total quantity sold among customers aged 30 or younger?

SELECT t.product_name,
       SUM(t.quantity) AS total_units
FROM transactions t
JOIN customers c ON t.customer_login = c.login
WHERE c.age <= 30
GROUP BY t.product_name
ORDER BY total_units DESC
LIMIT 1;

-- How much has each customer with an apartment ('Apt.') address spent in total?

SELECT c.login,
       c.first_name,
       c.last_name,
       COALESCE(SUM(p.price * t.quantity), 0) AS total_spent
FROM customers c
LEFT JOIN transactions t ON c.login = t.customer_login
LEFT JOIN products p ON t.product_name = p.name
WHERE c.address ILIKE '%Apt.%'
GROUP BY c.login, c.first_name, c.last_name
ORDER BY total_spent DESC;

-- Which customers have bought at least 3 different products?

SELECT c.login, c.first_name, c.last_name, COUNT(DISTINCT t.product_name) AS distinct_products
FROM customers c
JOIN transactions t ON c.login = t.customer_login
GROUP BY c.login, c.first_name, c.last_name
HAVING COUNT(DISTINCT t.product_name) >= 3
ORDER BY distinct_products DESC;

-- What is the average number of days after release that each product is purchased?

SELECT p.name AS product_name,
       ROUND(AVG(t.date_of_transaction::date - p.release_date::date), 1) AS avg_days_after_release
FROM products p
JOIN transactions t ON p.name = t.product_name
GROUP BY p.name
ORDER BY avg_days_after_release ASC;

-- Find customers who made purchases in both 2024 and 2025.

SELECT c.login, c.first_name, c.last_name
FROM customers c
JOIN transactions t ON c.login = t.customer_login
WHERE EXTRACT(YEAR FROM t.date_of_transaction) IN (2024, 2025)
GROUP BY c.login, c.first_name, c.last_name
HAVING COUNT(DISTINCT EXTRACT(YEAR FROM t.date_of_transaction)) = 2;

-- For each customer who made a purchase, find their single highest-revenue transaction.

WITH ranked_transactions AS (
    SELECT t.customer_login,
           t.id AS transaction_id,
           t.product_name,
           (p.price * t.quantity) AS revenue,
           ROW_NUMBER() OVER (
               PARTITION BY t.customer_login
               ORDER BY (p.price * t.quantity) DESC, t.date_of_transaction DESC, t.id DESC
           ) AS rn
    FROM transactions t
    JOIN products p ON t.product_name = p.name
)
SELECT customer_login, transaction_id, product_name, revenue
FROM ranked_transactions
WHERE rn = 1;

-- Calculate the cumulative running total of revenue by transaction date.

WITH daily_revenue AS (
    SELECT t.date_of_transaction,
           SUM(p.price * t.quantity) AS revenue
    FROM transactions t
    JOIN products p ON t.product_name = p.name
    GROUP BY t.date_of_transaction
)
SELECT date_of_transaction,
       revenue AS daily_revenue,
       SUM(revenue) OVER (ORDER BY date_of_transaction ASC) AS cumulative_revenue
FROM daily_revenue
ORDER BY date_of_transaction ASC;

-- Calculate the month-over-month percentage change in total units sold.

WITH monthly_units AS (
    SELECT DATE_TRUNC('month', date_of_transaction)::date AS month,
           SUM(quantity) AS units_sold
    FROM transactions
    GROUP BY month
)
SELECT month,
       units_sold,
       ROUND(
           (units_sold - LAG(units_sold) OVER (ORDER BY month)) * 100.0
           / NULLIF(LAG(units_sold) OVER (ORDER BY month), 0),
           2
       ) AS mom_growth_pct
FROM monthly_units
ORDER BY month ASC;

-- Identify the top 3 companies by revenue and their percentage share of total corporate revenue.


WITH company_revenue AS (
    SELECT c.company_name,
           SUM(p.price * t.quantity) AS revenue
    FROM customers c
    JOIN transactions t ON c.login = t.customer_login
    JOIN products p ON t.product_name = p.name
    WHERE c.company_name IS NOT NULL
    GROUP BY c.company_name
)
SELECT company_name,
       revenue,
       ROUND(revenue * 100.0 / NULLIF(SUM(revenue) OVER (), 0), 2) AS pct_of_corporate_revenue
FROM company_revenue
ORDER BY revenue DESC
LIMIT 3;

