\connect subscriptions

DROP TABLE IF EXISTS USERS CASCADE;
DROP TABLE IF EXISTS PLANS CASCADE;
DROP TABLE IF EXISTS SUBSCRIPTIONS CASCADE;
DROP TABLE IF EXISTS PAYMENTS CASCADE;

CREATE TABLE USERS(
    LOGIN VARCHAR(50) PRIMARY KEY,
    NAME VARCHAR(50) NOT NULL,
    AGE INT CHECK (AGE > 0),
    GENDER VARCHAR(20),
    SIGNUP_DATE DATE NOT NULL
);

CREATE TABLE PLANS(
    NAME VARCHAR(50) PRIMARY KEY,
    PRICE INT NOT NULL CHECK (PRICE > 0),
    BILLING_PERIOD VARCHAR(50) NOT NULL CHECK (BILLING_PERIOD IN ('daily', 'weekly', 'biweekly', 'monthly', 'quarterly', 'semiannual', 'annual', 'one_time'))
);

CREATE TABLE SUBSCRIPTIONS(
    ID VARCHAR(50) PRIMARY KEY,
    USER_LOGIN VARCHAR(50) REFERENCES USERS(LOGIN) NOT NULL,
    START_DATE DATE NOT NULL,
    END_DATE DATE,
    PLANS_NAME VARCHAR(50) REFERENCES PLANS(NAME) NOT NULL
);

CREATE TABLE PAYMENTS(
    ID VARCHAR(50) PRIMARY KEY,
    SUBSCRIPTION_ID VARCHAR(50) REFERENCES SUBSCRIPTIONS(ID) NOT NULL,
    AMOUNT INT NOT NULL CHECK (AMOUNT > 0),
    PAYMENT_METHOD VARCHAR(50) NOT NULL CHECK (PAYMENT_METHOD IN ('card', 'bank_transfer', 'paypal', 'apple_pay', 'google_pay', 'cash')),
    STATUS VARCHAR(50) NOT NULL CHECK (STATUS IN ('pending', 'paid', 'cancelled', 'failed', 'refunded')),
    PAYMENT_DATE DATE NOT NULL
);