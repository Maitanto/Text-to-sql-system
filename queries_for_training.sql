-- What is the average age of active subscribers for each plan?

SELECT s.plans_name,
       ROUND(AVG(u.age), 1) AS average_subscriber_age
FROM subscriptions s
JOIN users u ON s.user_login = u.login
WHERE s.end_date IS NULL
GROUP BY s.plans_name;

-- Calculate the current normalized Monthly Recurring Revenue (MRR) from active subscriptions, dividing annual plan prices by 12.

SELECT ROUND(
           SUM(
               CASE
                   WHEN pl.billing_period = 'annual' THEN pl.price / 12.0
                   ELSE pl.price
               END
           ),
           2
       ) AS current_mrr
FROM subscriptions s
JOIN plans pl ON s.plans_name = pl.name
WHERE s.end_date IS NULL;

-- For each plan, calculate the churn percentage (ended subscriptions out of total subscriptions).

SELECT pl.name AS plans_name,
       COUNT(s.id) AS total_subscriptions,
       COUNT(s.end_date) AS churned_subscriptions,
       ROUND(COUNT(s.end_date) * 100.0 / NULLIF(COUNT(s.id), 0), 2) AS churn_rate_pct
FROM plans pl
LEFT JOIN subscriptions s ON pl.name = s.plans_name
GROUP BY pl.name
ORDER BY churn_rate_pct DESC NULLS LAST;

-- Count distinct subscribers broken down by gender and billing period.

SELECT u.gender,
       pl.billing_period,
       COUNT(DISTINCT u.login) AS unique_users
FROM users u
JOIN subscriptions s ON u.login = s.user_login
JOIN plans pl ON s.plans_name = pl.name
GROUP BY u.gender, pl.billing_period
ORDER BY u.gender, pl.billing_period;

-- Which calendar month generated the highest total revenue from paid payments?

SELECT DATE_TRUNC('month', p.payment_date)::date AS revenue_month,
       SUM(pl.price) AS total_revenue
FROM payments p
JOIN subscriptions s ON p.subscription_id = s.id
JOIN plans pl ON s.plans_name = pl.name
WHERE p.status = 'paid'
