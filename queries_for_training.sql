-- Calculate the average number of days between a user's signup date and the start date of their first subscription.

WITH first_subscriptions AS (
    SELECT user_login,
           MIN(start_date) AS first_sub_date
    FROM subscriptions
    GROUP BY user_login
)
SELECT ROUND(AVG(fs.first_sub_date::date - u.signup_date::date), 1) AS avg_days_to_first_sub
FROM users u
JOIN first_subscriptions fs ON u.login = fs.user_login;

-- Find currently active subscriptions whose most recent payment attempt was cancelled.

WITH latest_payments AS (
    SELECT subscription_id,
           status,
           ROW_NUMBER() OVER (
               PARTITION BY subscription_id
               ORDER BY payment_date DESC, id DESC
           ) AS rn
    FROM payments
)
SELECT s.id AS subscription_id, s.user_login, s.plans_name
FROM subscriptions s
JOIN latest_payments lp ON s.id = lp.subscription_id
WHERE s.end_date IS NULL
  AND lp.rn = 1
  AND lp.status = 'cancelled';

-- For users who have had multiple subscriptions, show each subscription alongside their immediately preceding plan ordered by start date.

WITH user_sub_history AS (
    SELECT id AS subscription_id,
           user_login,
           plans_name AS current_plan,
           LAG(plans_name) OVER (PARTITION BY user_login ORDER BY start_date ASC, id ASC) AS previous_plan,
           start_date,
           COUNT(*) OVER (PARTITION BY user_login) AS total_user_subs
    FROM subscriptions
)
SELECT user_login,
       subscription_id,
       current_plan,
       previous_plan,
       start_date
FROM user_sub_history
WHERE total_user_subs > 1
ORDER BY user_login, start_date ASC, subscription_id ASC;

-- Find active subscriptions that started more than 30 days before January 1, 2026 and have no paid payments.

SELECT s.id AS subscription_id, s.user_login, s.plans_name, s.start_date
FROM subscriptions s
LEFT JOIN payments p
       ON s.id = p.subscription_id AND p.status = 'paid'
WHERE s.end_date IS NULL
  AND s.start_date < DATE '2026-01-01' - INTERVAL '30 days'
  AND p.id IS NULL;

-- Find users who have at least one payment record, yet zero paid payments.

SELECT u.login, u.first_name, u.last_name
