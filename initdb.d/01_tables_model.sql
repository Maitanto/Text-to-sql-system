\connect transactions

DROP TABLE IF EXISTS CUSTOMERS CASCADE;
DROP TABLE IF EXISTS PRODUCTS CASCADE;
DROP TABLE IF EXISTS TRANSACTIONS CASCADE;


CREATE TABLE CUSTOMERS(
    LOGIN VARCHAR(50) PRIMARY KEY,
    FIRST_NAME VARCHAR(50) NOT NULL,
    LAST_NAME VARCHAR(50) NOT NULL,
    AGE INT CHECK (AGE > 0),
    GENDER VARCHAR(20),
    ADDRESS VARCHAR(255),
    COMPANY_NAME VARCHAR(50)
);

CREATE TABLE PRODUCTS(
    NAME VARCHAR(50) PRIMARY KEY,
    PRICE NUMERIC(7, 2) NOT NULL CHECK (PRICE > 0), 
    RELEASE_DATE DATE NOT NULL,
    COST_OF_PRODUCTION NUMERIC(7, 2) NOT NULL CHECK (COST_OF_PRODUCTION > 0)
);

CREATE TABLE TRANSACTIONS(
    ID VARCHAR(50) PRIMARY KEY,
    PRODUCT_NAME VARCHAR(50) NOT NULL,
    CUSTOMER_LOGIN VARCHAR(50) NOT NULL,
    DATE_OF_TRANSACTION DATE NOT NULL,
    QUANTITY INT NOT NULL CHECK (QUANTITY > 0),
    CONSTRAINT fk_transactions_product FOREIGN KEY (PRODUCT_NAME) REFERENCES PRODUCTS(NAME), 
    CONSTRAINT fk_transactions_customer FOREIGN KEY (CUSTOMER_LOGIN) REFERENCES CUSTOMERS(LOGIN)
);